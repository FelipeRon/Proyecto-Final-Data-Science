-- Configuración única del PSet 2. Ejecutar en Snowsight con ACCOUNTADMIN.
-- Antes: sustituir <RSA_PUBLIC_KEY_BASE64> por la llave PÚBLICA propia (sin cabeceras).
-- Nunca pegar la llave privada. Para usuarios existentes, revisar antes el ALTER USER:
-- actualiza la llave principal y puede afectar otras conexiones del mismo usuario.
USE ROLE ACCOUNTADMIN;

-- Presupuesto acumulado: no se reinicia mensualmente. Cambiar cuota conscientemente.
-- Es protección de créditos del warehouse, no un límite monetario exacto de toda la cuenta.
CREATE RESOURCE MONITOR IF NOT EXISTS PSET2_MONITOR
  WITH CREDIT_QUOTA = 20 FREQUENCY = NEVER START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
CREATE WAREHOUSE IF NOT EXISTS PSET2_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE PSET2_WH SET RESOURCE_MONITOR = PSET2_MONITOR;

CREATE DATABASE IF NOT EXISTS PSET2;
CREATE SCHEMA IF NOT EXISTS PSET2.RAW;     -- snapshots: reemplazo idempotente por hash
CREATE SCHEMA IF NOT EXISTS PSET2.BRONZE;  -- dbt: staging tipado
CREATE SCHEMA IF NOT EXISTS PSET2.SILVER;  -- dbt: calidad, limpieza y cuarentena
CREATE SCHEMA IF NOT EXISTS PSET2.GOLD;    -- dbt: hecho y dimensión
CREATE SCHEMA IF NOT EXISTS PSET2.OBT;     -- Spark: tabla ancha
CREATE ROLE IF NOT EXISTS PSET2_ROLE;
GRANT USAGE ON WAREHOUSE PSET2_WH TO ROLE PSET2_ROLE;
GRANT USAGE ON DATABASE PSET2 TO ROLE PSET2_ROLE;

-- Sin ALL PRIVILEGES, OWNERSHIP ni CREATE SCHEMA; sin acceso a otras bases.
-- El mismo rol crea y posee las tablas de todas las etapas.
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT
  ON SCHEMA PSET2.RAW TO ROLE PSET2_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT
  ON SCHEMA PSET2.BRONZE TO ROLE PSET2_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT
  ON SCHEMA PSET2.SILVER TO ROLE PSET2_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT
  ON SCHEMA PSET2.GOLD TO ROLE PSET2_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT
  ON SCHEMA PSET2.OBT TO ROLE PSET2_ROLE;
GRANT ROLE PSET2_ROLE TO ROLE SYSADMIN;

-- Usuario dedicado nuevo: sin contraseña y sin inicio interactivo.
CREATE USER IF NOT EXISTS PSET2_SVC TYPE = SERVICE
  DEFAULT_ROLE = PSET2_ROLE DEFAULT_WAREHOUSE = PSET2_WH;
ALTER USER PSET2_SVC SET RSA_PUBLIC_KEY = '<RSA_PUBLIC_KEY_BASE64>';
GRANT ROLE PSET2_ROLE TO USER PSET2_SVC;

SELECT CURRENT_ORGANIZATION_NAME() || '-' || CURRENT_ACCOUNT_NAME() AS snowflake_account;
SHOW GRANTS TO ROLE PSET2_ROLE;
SHOW GRANTS TO USER PSET2_SVC;
SHOW RESOURCE MONITORS LIKE 'PSET2_MONITOR';
DESCRIBE USER PSET2_SVC; -- comprobar RSA_PUBLIC_KEY_FP
